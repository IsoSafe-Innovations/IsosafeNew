#!/usr/bin/env bash
# Day-6 first manual deploy for the cloud VM provisioned by infra/demo/.
#
# Run ON the VM (Ubuntu 24.04; cloud-init already installed Docker):
#
#   DOMAIN=demo.isosafe.com ACME_EMAIL=owner@isosafe.com \
#   S3_BUCKET=isosafe-demo-snapshots \
#   sudo -E bash deploy/first_deploy.sh
#
# Idempotent: re-runs pull the requested ref, keep the existing root-only
# .env, renew the certificate when due, and recreate changed containers.
#
# Required env: DOMAIN, ACME_EMAIL, S3_BUCKET
# Optional env: REPO_URL, REPO_REF (default main), APP_DIR, S3_REGION,
#               JWT_SECRET, AGENT_TOKEN, FERNET_KEY, POSTGRES_PASSWORD,
#               BOOTSTRAP_ADMIN_EMAIL, BOOTSTRAP_ADMIN_PASSWORD, ADMIN_EMAIL
set -euo pipefail

log() { printf '\n\033[1;34m== %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33mWARN: %s\033[0m\n' "$*" >&2; }

DOMAIN="${DOMAIN:?set DOMAIN, e.g. demo.isosafe.com}"
ACME_EMAIL="${ACME_EMAIL:?set ACME_EMAIL for the TLS certificate}"
S3_BUCKET="${S3_BUCKET:?set S3_BUCKET to the bucket created by infra/demo}"
REPO_URL="${REPO_URL:-https://github.com/IsoSafe-Innovations/IsosafeNew.git}"
REPO_REF="${REPO_REF:-main}"
APP_DIR="${APP_DIR:-/opt/isosafe/app}"
S3_REGION="${S3_REGION:-us-east-1}"
BOOTSTRAP_ADMIN_EMAIL="${BOOTSTRAP_ADMIN_EMAIL:-admin@isosafe.local}"

COMPOSE_FILES=(-f docker-compose.yml -f docker-compose.cloud.yml -f docker-compose.aws.yml)
compose() { docker compose "${COMPOSE_FILES[@]}" "$@"; }
gen_hex() { openssl rand -hex 32; }
gen_fernet() { openssl rand -base64 32 | tr '+/' '-_'; }

if [[ $EUID -ne 0 ]]; then
  echo "run as root: sudo -E bash deploy/first_deploy.sh" >&2
  exit 1
fi
command -v docker >/dev/null || { echo "docker not installed" >&2; exit 1; }
docker compose version >/dev/null

# --- 1. Code -----------------------------------------------------------------
log "Fetching $REPO_REF into $APP_DIR"
if [[ -d "$APP_DIR/.git" ]]; then
  git -C "$APP_DIR" fetch --depth 1 origin "$REPO_REF"
  git -C "$APP_DIR" checkout -q FETCH_HEAD
else
  mkdir -p "$(dirname "$APP_DIR")"
  if ! git clone --depth 1 --branch "$REPO_REF" "$REPO_URL" "$APP_DIR" 2>/dev/null; then
    git clone "$REPO_URL" "$APP_DIR"
    git -C "$APP_DIR" checkout -q "$REPO_REF"
  fi
fi
cd "$APP_DIR"
mkdir -p deploy/certs deploy/acme deploy/backups

# --- 2. Secrets / root-only .env --------------------------------------------
ENV_FILE="$APP_DIR/.env"
if [[ ! -f "$ENV_FILE" ]]; then
  log "Writing root-only .env (secrets generated where not supplied)"
  JWT_SECRET="${JWT_SECRET:-$(gen_hex)}"
  AGENT_TOKEN="${AGENT_TOKEN:-$(gen_hex)}"
  FERNET_KEY="${FERNET_KEY:-$(gen_fernet)}"
  POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-$(gen_hex)}"
  BOOTSTRAP_ADMIN_PASSWORD="${BOOTSTRAP_ADMIN_PASSWORD:-$(gen_hex)}"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/first_deploy.sh - root-only, never commit.
POSTGRES_USER=isosafe
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
POSTGRES_DB=isosafe
DATABASE_URL=postgresql+asyncpg://isosafe:$POSTGRES_PASSWORD@postgres:5432/isosafe
REDIS_URL=redis://redis:6379/0
HTTP_PORT=80
HTTPS_PORT=443
API_WORKERS=2

JWT_SECRET=$JWT_SECRET
CAMERA_SECRET_KEY=$FERNET_KEY
FERNET_KEY=$FERNET_KEY
BOOTSTRAP_ADMIN_EMAIL=$BOOTSTRAP_ADMIN_EMAIL
BOOTSTRAP_ADMIN_PASSWORD=$BOOTSTRAP_ADMIN_PASSWORD
ACCESS_TOKEN_MINUTES=30
REFRESH_TOKEN_DAYS=7
CORS_ORIGINS=https://$DOMAIN

AGENT_MODE=1
AGENT_TOKEN=$AGENT_TOKEN

# Real S3: empty endpoint/keys -> VM IAM instance role (infra/demo/iam.tf).
S3_ENDPOINT_URL=
S3_PUBLIC_ENDPOINT_URL=
S3_REGION=$S3_REGION
S3_BUCKET=$S3_BUCKET
S3_ACCESS_KEY=
S3_SECRET_KEY=
S3_PRESIGN_PUT_SECONDS=300
S3_PRESIGN_GET_SECONDS=300
EOF
  chmod 600 "$ENV_FILE"
  ADMIN_SHOWN="$BOOTSTRAP_ADMIN_PASSWORD"
else
  log ".env already present; keeping it (delete to rotate secrets)"
  ADMIN_SHOWN=""
fi
# shellcheck disable=SC1090
set -a; . "$ENV_FILE"; set +a

# --- 3. Self-signed cert so nginx can start, then ACME -----------------------
if [[ ! -f deploy/certs/server.crt ]]; then
  log "Seeding a self-signed certificate (replaced by Let's Encrypt below)"
  openssl req -x509 -nodes -newkey rsa:2048 -days 1 \
    -keyout deploy/certs/server.key -out deploy/certs/server.crt \
    -subj "/CN=$DOMAIN" 2>/dev/null
fi

# --- 4. Bring the stack up ---------------------------------------------------
log "Building and starting the stack (nginx + TLS)"
compose up -d --build

log "Waiting for backend health"
healthy=0
for _ in $(seq 1 60); do
  if compose exec -T backend curl -fsS http://localhost:8000/api/health >/dev/null 2>&1; then
    healthy=1; break
  fi
  sleep 5
done
[[ $healthy -eq 1 ]] || { warn "backend did not become healthy"; compose logs --tail=80 backend; exit 1; }

# --- 5. Let's Encrypt certificate -------------------------------------------
log "Obtaining/renewing Let's Encrypt certificate for $DOMAIN"
docker run --rm \
  -v "$APP_DIR/deploy/certs:/etc/letsencrypt" \
  -v "$APP_DIR/deploy/acme:/var/www/acme" \
  certbot/certbot certonly --webroot -w /var/www/acme \
  -d "$DOMAIN" --email "$ACME_EMAIL" --agree-tos --no-eff-email \
  --non-interactive --keep-until-expiring
install -m 644 "deploy/certs/live/$DOMAIN/fullchain.pem" deploy/certs/server.crt
install -m 600 "deploy/certs/live/$DOMAIN/privkey.pem" deploy/certs/server.key
compose exec -T nginx nginx -s reload

# --- 5b. Cert renewal timer --------------------------------------------------
log "Installing systemd timer for certificate renewal"
chmod +x deploy/renew_certs.sh
install -d -m 755 /etc/isosafe
cat > /etc/isosafe/deploy.env <<EOF
DOMAIN=$DOMAIN
APP_DIR=$APP_DIR
EOF
chmod 600 /etc/isosafe/deploy.env
cat > /etc/systemd/system/isosafe-certbot-renew.service <<EOF
[Unit]
Description=Iso Safe Let's Encrypt renewal
After=docker.service network-online.target
Wants=network-online.target
Requires=docker.service

[Service]
Type=oneshot
EnvironmentFile=/etc/isosafe/deploy.env
ExecStart=$APP_DIR/deploy/renew_certs.sh
EOF
cat > /etc/systemd/system/isosafe-certbot-renew.timer <<'EOF'
[Unit]
Description=Run Iso Safe certificate renewal twice daily

[Timer]
OnCalendar=*-*-* 03,15:17:00
RandomizedDelaySec=1800
Persistent=true

[Install]
WantedBy=timers.target
EOF
systemctl daemon-reload
systemctl enable --now isosafe-certbot-renew.timer

# --- 6. Verify the public front door ----------------------------------------
log "Checking https://$DOMAIN/ (Day-6 target: login page)"
TLS_OK=1
if ! curl -fsS -o /tmp/isosafe-index.html "https://$DOMAIN/"; then
  TLS_OK=0
  warn "trusted TLS failed; retrying with -k (certificate may still be issuing)"
  curl -kfsS -o /tmp/isosafe-index.html "https://$DOMAIN/" || true
fi
if grep -q '<title>Iso Safe</title>' /tmp/isosafe-index.html 2>/dev/null; then
  echo "  PASS login page served at https://$DOMAIN/"
else
  warn "index page did not look like the Iso Safe login page"
fi
if curl -kfsS "https://$DOMAIN/api/health" | grep -q '"ok":true'; then
  echo "  PASS /api/health reports database ok"
else
  warn "/api/health did not report healthy"
fi

log "Done"
echo "  URL:   https://$DOMAIN/"
echo "  admin: $BOOTSTRAP_ADMIN_EMAIL"
if [[ -n "$ADMIN_SHOWN" ]]; then
  echo "  password: $ADMIN_SHOWN   (change after first login)"
else
  echo "  password: see $ENV_FILE (BOOTSTRAP_ADMIN_PASSWORD)"
fi
if [[ $TLS_OK -eq 0 ]]; then
  warn "Certificate was not yet trusted; re-run this script once DNS/certbot settles."
fi